const toThanas = (list, inside) => list.map(([name, bn]) => ({ name, bn, inside }));

// Dhaka first (most orders), then the rest alphabetically.
export const DISTRICTS = [
  {
    name: DHAKA,
    bn: "ঢাকা",
    thanas: [...toThanas(DHAKA_CITY_THANAS, true), ...toThanas(DHAKA_OUTER_UPAZILAS, false)],
  },
  ...OTHER_DISTRICTS.map(([name, bn, thanas]) => ({ name, bn, thanas: toThanas(thanas, false) })),
];

export function getDistrict(name) {
  return DISTRICTS.find((d) => d.name === name) || null;
}

export function getThana(districtName, thanaName) {
  return getDistrict(districtName)?.thanas.find((t) => t.name === thanaName) || null;
}

// "inside" | "outside", or null while it can't be decided yet (no district,
// or Dhaka district without a thana).
export function deliveryZone(districtName, thanaName) {
  const district = getDistrict(districtName);
  if (!district) return null;
  if (district.name !== DHAKA) return "outside";
  const thana = getThana(districtName, thanaName);
  if (!thana) return null;
  return thana.inside ? "inside" : "outside";
}

// One-line delivery address, e.g. "House 104, Road-6, Bashundhara R/A, Dhaka - Vatara".
// Used for the customer's preview and for what is sent to the sheet, so both match.
export function formatFullAddress(address, districtName, thanaName) {
  const street = String(address || "")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/[\s,.;-]+$/, "");
  const area = [districtName, thanaName].filter(Boolean).join(" - ");
  return [street, area].filter(Boolean).join(", ");
}

export function deliveryCharge(districtName, thanaName) {
  const zone = deliveryZone(districtName, thanaName);
  return zone ? DELIVERY_CHARGE[zone] : null;
}
